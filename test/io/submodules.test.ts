import { chmod, mkdir, symlink } from 'node:fs/promises';
import path from 'node:path';

import { afterEach, describe, expect, it } from 'vitest';

import { pathStatus } from '../../src/core/paths.js';
import {
  isOpaqueSubmodule,
  MAX_GITMODULES_BYTES,
  parseGitmodules,
} from '../../src/io/submodules.js';
import { walk } from '../../src/io/walk.js';
import {
  canDenyPermissions,
  filePaths,
  makeDirs,
  makeTempDir,
  removeTempDirs,
  symlinksSupported,
  writeTree,
} from './helpers.js';

afterEach(removeTempDirs);

function gitmodules(...paths: string[]): string {
  return paths
    .map(
      (p, index) =>
        `[submodule "m${String(index)}"]\n\tpath = ${p}\n\turl = https://x/${String(index)}.git\n`,
    )
    .join('');
}

describe('parseGitmodules', () => {
  it('reads the path of every submodule section', () => {
    const text = [
      '# generated by git',
      '[submodule "libs/one"]',
      '\tpath = libs/one',
      '\turl = https://example.com/one.git',
      '[submodule "two"]',
      '    path = third_party/two',
      '    branch = main',
      '',
    ].join('\r\n');
    expect(parseGitmodules(text)).toEqual(['libs/one', 'third_party/two']);
  });

  it('handles quoting, escapes, comments, case and the legacy section syntax', () => {
    const text = [
      '[Submodule "a"]',
      '  PATH = "dir with spaces" ; comment',
      '[submodule "b"]',
      'path=plain#comment',
      '[submodule "c"]',
      '  path = "quo\\"ted"  ',
      '[submodule "d"]',
      '  path = with\\ttab',
      '[submodule.legacy]',
      '  path = legacy',
      '[submodule "e"]',
      '  path = spaced  out   # trailing spaces and comment dropped',
    ].join('\n');
    expect(parseGitmodules(text)).toEqual([
      'dir with spaces',
      'legacy',
      'plain',
      'quo"ted',
      'spaced  out',
      'with\ttab',
    ]);
  });

  it('only reads `path` keys inside named submodule sections', () => {
    const text = [
      'path = before-any-section',
      '[core]',
      '  path = core-path',
      '[submodule]',
      '  path = unnamed',
      '[submodules "x"]',
      '  path = wrong-section',
      '[submodule "ok"]',
      '  paths = not-path',
      '  path',
      '  url = path = nope',
      '  path = kept',
    ].join('\n');
    expect(parseGitmodules(text)).toEqual(['kept']);
  });

  it('drops absolute, climbing, Windows-style and unparseable paths', () => {
    const text = gitmodules(
      '/etc',
      'C:\\\\Windows',
      'C:/Windows',
      '../outside',
      'a/../../b',
      'a/..',
      'dir\\\\..\\\\up',
      '"unterminated',
      'bad\\q',
      'trailing\\',
      '.',
      '""',
    );
    expect(parseGitmodules(text)).toEqual([]);
  });

  it('normalizes, deduplicates and sorts', () => {
    expect(parseGitmodules(gitmodules('./b//c/', 'a', 'b/c', 'a/./'))).toEqual(['a', 'b/c']);
  });
});

describe('isOpaqueSubmodule', () => {
  it('hides uninitialized submodules and checkouts outside hidden directories', () => {
    expect(isOpaqueSubmodule('libs/one', [])).toBe(true);
    expect(isOpaqueSubmodule('.claude/skills', [])).toBe(true);
    expect(isOpaqueSubmodule('libs/one', ['.git', 'AGENTS.md'])).toBe(true);
  });

  it('walks checkouts in hidden directories and directories that are not checkouts', () => {
    expect(isOpaqueSubmodule('.claude/skills', ['.git', 'x'])).toBe(false);
    expect(isOpaqueSubmodule('tools/.cursor/rules', ['.git'])).toBe(false);
    expect(isOpaqueSubmodule('libs/one', ['AGENTS.md'])).toBe(false);
  });
});

describe('walk: submodules', () => {
  it('marks uninitialized and checked-out submodules opaque', async () => {
    const root = await makeTempDir();
    await writeTree(root, {
      '.gitmodules': gitmodules('libs/one', 'third_party/two', 'gone/three'),
      'third_party/two/.git': 'gitdir: ../../.git/modules/two\n',
      'third_party/two/AGENTS.md': 'upstream instructions',
      'AGENTS.md': 'mine',
    });
    await makeDirs(root, 'libs/one', 'gone');

    const snapshot = await walk(root);

    expect(filePaths(snapshot)).toEqual(['AGENTS.md']);
    expect([...snapshot.opaqueDirectories]).toEqual([
      'gone/three/',
      'libs/one/',
      'third_party/two/',
    ]);
    expect(snapshot.paths.has('libs/one/')).toBe(true);
    expect(snapshot.paths.has('third_party/two/')).toBe(true);
    expect(snapshot.paths.has('third_party/two/AGENTS.md')).toBe(false);
    // Not on disk at all (an archive without submodules): opaque, but not listed as seen.
    expect(snapshot.paths.has('gone/three/')).toBe(false);
    expect(
      Object.fromEntries(
        [
          'libs/one/README.md',
          'third_party/two/AGENTS.md',
          'gone/three/README.md',
          'gone/three',
          'libs/other/README.md',
        ].map((p) => [p, pathStatus(snapshot, p)]),
      ),
    ).toEqual({
      'libs/one/README.md': 'unknown',
      'third_party/two/AGENTS.md': 'unknown',
      'gone/three/README.md': 'unknown',
      'gone/three': 'exists',
      'libs/other/README.md': 'missing',
    });
  });

  it('cannot be used to hide agent configuration', async () => {
    const root = await makeTempDir();
    await writeTree(root, {
      '.gitmodules': gitmodules('.claude', 'src', '.cursor/rules', '.agents/skills'),
      // Committed directories, not checkouts: a repository cannot commit a `.git` entry.
      '.claude/settings.json': '{"hooks":{}}',
      'src/CLAUDE.md': 'nested instructions',
      // A real checkout, but where agents load configuration from: still walked.
      '.agents/skills/.git': 'gitdir: ../../.git/modules/skills\n',
      '.agents/skills/demo/SKILL.md': '---\nname: demo\n---\n',
    });
    await makeDirs(root, '.cursor/rules');

    const snapshot = await walk(root);

    expect(filePaths(snapshot)).toEqual([
      '.agents/skills/demo/SKILL.md',
      '.claude/settings.json',
      'src/CLAUDE.md',
    ]);
    // An empty directory hides nothing, so an uninitialized one is opaque even here.
    expect([...snapshot.opaqueDirectories]).toEqual(['.cursor/rules/']);
  });

  it('ignores unsafe entries and adds nothing for paths that are files or already opaque', async () => {
    const root = await makeTempDir();
    await writeTree(root, {
      '.gitmodules': gitmodules(
        '/etc',
        '../outside',
        'a/../../b',
        'NOTES.md',
        'vendor/lib',
        'gen/x',
      ),
      '.gitignore': 'gen/\n',
      'NOTES.md': 'a file',
      'vendor/lib/AGENTS.md': 'vendored',
      'gen/x/AGENTS.md': 'generated',
    });
    const snapshot = await walk(root);
    expect([...snapshot.opaqueDirectories]).toEqual(['gen/', 'vendor/']);
    expect(snapshot.paths.has('NOTES.md')).toBe(true);
  });

  it('only reads the root .gitmodules', async () => {
    const root = await makeTempDir();
    await writeTree(root, { 'sub/.gitmodules': gitmodules('x') });
    await makeDirs(root, 'sub/x');
    const snapshot = await walk(root);
    expect(snapshot.opaqueDirectories).toEqual(new Set());
    expect(snapshot.paths.has('sub/x/')).toBe(true);
  });

  it('marks submodules the entry limit kept from being listed', async () => {
    const root = await makeTempDir();
    await writeTree(root, { '.gitmodules': gitmodules('z-mod'), 'a/AGENTS.md': 'a' });
    await makeDirs(root, 'z-mod');
    // With no entry budget the root is never listed, yet the declared path is known.
    const snapshot = await walk(root, { maxEntries: 0 });
    expect(snapshot.skipped.map((entry) => entry.reason)).toEqual(['file-limit']);
    expect(snapshot.opaqueDirectories).toEqual(new Set(['z-mod/']));
    expect(pathStatus(snapshot, 'z-mod/README.md')).toBe('unknown');
  });

  it('skips a .gitmodules larger than 64 KiB and does not apply it', async () => {
    const root = await makeTempDir();
    const text = `${gitmodules('libs/one')}#${'x'.repeat(MAX_GITMODULES_BYTES)}\n`;
    await writeTree(root, { '.gitmodules': text });
    await makeDirs(root, 'libs/one');
    const snapshot = await walk(root);
    expect(MAX_GITMODULES_BYTES).toBe(64 * 1024);
    expect(snapshot.skipped).toEqual([
      { path: '.gitmodules', reason: 'too-large', size: Buffer.byteLength(text) },
    ]);
    expect(snapshot.opaqueDirectories).toEqual(new Set());
    // .gitmodules has nothing to do with .gitignore.
    expect(snapshot.gitignoreApplied).toBe(true);
  });

  it('ignores a .gitmodules that is a directory', async () => {
    const root = await makeTempDir();
    await mkdir(path.join(root, '.gitmodules'));
    await makeDirs(root, 'libs/one');
    const snapshot = await walk(root);
    expect(snapshot.opaqueDirectories).toEqual(new Set());
  });

  it.skipIf(!symlinksSupported)('does not follow a symlinked .gitmodules', async () => {
    const root = await makeTempDir();
    await writeTree(root, { 'modules.txt': gitmodules('libs/one') });
    await symlink('modules.txt', path.join(root, '.gitmodules'));
    await makeDirs(root, 'libs/one');
    const snapshot = await walk(root);
    expect(snapshot.opaqueDirectories).toEqual(new Set());
  });

  it.skipIf(!canDenyPermissions)('reports an unreadable .gitmodules', async () => {
    const root = await makeTempDir();
    await writeTree(root, { '.gitmodules': gitmodules('libs/one') });
    await makeDirs(root, 'libs/one');
    const file = path.join(root, '.gitmodules');
    await chmod(file, 0o000);
    try {
      const snapshot = await walk(root);
      expect(snapshot.skipped).toEqual([{ path: '.gitmodules', reason: 'unreadable' }]);
      expect(snapshot.opaqueDirectories).toEqual(new Set());
    } finally {
      await chmod(file, 0o600);
    }
  });
});
